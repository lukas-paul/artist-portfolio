const HOST_MATCHERS: [RegExp, string][] = [
  [/(?:^|\.)instagram\.com$/, "instagram"],
  [/(?:^|\.)(?:facebook\.com|fb\.com)$/, "facebook"],
  [/(?:^|\.)(?:x\.com|twitter\.com)$/, "x"],
  [/(?:^|\.)(?:youtube\.com|youtu\.be)$/, "youtube"],
  [/(?:^|\.)linkedin\.com$/, "linkedin"],
  [/(?:^|\.)tiktok\.com$/, "tiktok"],
  [/(?:^|\.)vimeo\.com$/, "vimeo"],
];

function detect(href?: string | null): string {
  if (!href) return "globe";
  if (href.startsWith("mailto:")) return "mail";
  let host: string;
  try {
    host = new URL(href).hostname.replace(/^www\./, "");
  } catch {
    return "globe";
  }
  return HOST_MATCHERS.find(([pattern]) => pattern.test(host))?.[1] ?? "globe";
}

